"""Declarative base, naming conventions, and the shared column mixins.

TRD 2.4: "Every tenant-scoped table carries `tenant_id UUID NOT NULL
REFERENCES tenants(id)` as its first non-key column, and is covered by a
Row-Level Security policy of the same shape."

`TenantScopedMixin` is how that first half is made structural rather than
conventional — a new tenant-scoped table cannot forget the column, get its
type wrong, or index it differently. The second half (the policy) is enforced
by migration 0002 plus the drift test in tests/test_rls_isolation.py.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, MetaData, text
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, declared_attr, mapped_column

# Deterministic constraint names. Without this, Alembic emits autogenerated
# names for CHECK/FK constraints that differ between environments, and a
# downgrade that has to DROP CONSTRAINT by name becomes a guessing game.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


# --- Column factories ---------------------------------------------------------
# These return a *new* mapped_column per call; mapped_column instances cannot
# be shared between classes.


def uuid_pk() -> Mapped[uuid.UUID]:
    """UUID primary key with the FIG 2.1 server-side default."""
    return mapped_column(
        PGUUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
        sort_order=-100,
    )


def created_at_column() -> Mapped[datetime]:
    return mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=text("now()"),
        sort_order=100,
    )


class TenantScopedMixin:
    """Adds the `tenant_id` column required of every tenant-scoped table.

    `sort_order=-50` places it immediately after the primary key, matching
    TRD 2.4's "first non-key column". Physical column order is cosmetic to
    Postgres, but it makes a `\d` of any table in this schema read the same
    way, which is worth the one keyword.

    ON DELETE CASCADE: deleting a tenant removes that tenant's data outright.
    That is the correct behaviour for a tenancy root — a half-deleted tenant
    leaving orphaned clusters behind is worse than either outcome — but it is
    a real gun, so tenant deletion should be an operator action, not an API
    route.
    """

    @declared_attr
    def tenant_id(cls) -> Mapped[uuid.UUID]:
        return mapped_column(
            PGUUID(as_uuid=True),
            ForeignKey("tenants.id", ondelete="CASCADE"),
            nullable=False,
            index=True,
            sort_order=-50,
        )
